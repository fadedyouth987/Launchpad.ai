// Writes dist/public/_headers for the Cloudflare (Workers static assets) build of the web app:
// the same security headers Express/helmet sends, with the API origin (VITE_API_BASE_URL) and the
// Neon Auth origin (VITE_NEON_AUTH_URL or NEON_AUTH_BASE_URL) added to connect-src, plus long-lived caching for hashed assets. Run after `vite build` (npm run build:web).
import '../server/loadEnv';
import fs from 'node:fs';
import path from 'node:path';
import { cspDirectives, cspHeaderValue, neonAuthOrigin } from '../server/csp';

const outDir = path.resolve(process.argv[2] || 'dist/public');
const raw = (process.env.VITE_API_BASE_URL || '').trim();
let apiOrigins: string[] = [];
if (raw) {
  const url = new URL(raw); // throws on garbage, failing the build
  if (url.protocol !== 'https:' && url.hostname !== 'localhost') {
    throw new Error(`VITE_API_BASE_URL must use https (got ${raw}).`);
  }
  apiOrigins = [url.origin];
} else {
  console.warn('[web-headers] VITE_API_BASE_URL is empty: the web app will call /api on its own origin.');
}

const authOrigin = neonAuthOrigin();
if (!authOrigin)
  console.warn('[web-headers] No VITE_NEON_AUTH_URL / NEON_AUTH_BASE_URL: sign-in will be blocked by CSP.');
const csp = cspHeaderValue(cspDirectives(apiOrigins, authOrigin));
const lines = [
  '# Generated by scripts/write-web-headers.ts. Do not edit by hand.',
  '/*',
  `  Content-Security-Policy: ${csp}`,
  '  Strict-Transport-Security: max-age=15552000; includeSubDomains',
  '  X-Content-Type-Options: nosniff',
  '  X-Frame-Options: DENY',
  '  Referrer-Policy: strict-origin-when-cross-origin',
  '  Cross-Origin-Opener-Policy: same-origin-allow-popups',
  '  Cross-Origin-Resource-Policy: same-origin',
  '  Origin-Agent-Cluster: ?1',
  '  X-DNS-Prefetch-Control: off',
  '  X-Permitted-Cross-Domain-Policies: none',
  '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()',
  '/assets/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
];
if (!fs.existsSync(path.join(outDir, 'index.html')))
  throw new Error(`No web build in ${outDir}; run vite build first.`);
fs.writeFileSync(path.join(outDir, '_headers'), lines.join('\n'));
console.log(
  `[web-headers] wrote ${path.join(outDir, '_headers')} (connect-src API: ${apiOrigins.join(', ') || 'same origin'}; auth: ${authOrigin || 'none'})`,
);
